#!/usr/bin/env python3
"""C1's result: `kvsim calibrate` on a real T4, against the rules registered before the run.

    python scripts/c1_analyze.py      # artifacts/results/c1_kaggle_t4/ -> report.md

C1 holds only if both hold (configs/c1_calibrate.yaml; docs/09, 2026-09-28):
  C1a — the command exits 0, its check within the error limit, and EVERY check request's cached
        tokens equal the model's (the registered prediction: exact);
  C1b — the KV capacity it reads equals the engine log's `GPU KV cache size` ÷ block size.
Both are recomputed here from the raw files, not copied from the notebook's own verdict. The fitted
timings against Phase 3's were registered as reported, not tested.
"""

from __future__ import annotations

import json
import pathlib
import re
import statistics

REPO = pathlib.Path(__file__).resolve().parents[1]
OUT = REPO / "artifacts" / "results" / "c1_kaggle_t4"
PREREG = REPO / "artifacts" / "results" / "c1_prereg" / "prediction.json"


def main() -> int:
    c1 = json.loads((OUT / "c1.json").read_text())
    prof = json.loads((OUT / "calibrated_profile.json").read_text())
    prereg = json.loads(PREREG.read_text())
    src, pred = prof["_source"], prereg["prediction"]
    chk = src["check"]
    log = (OUT / "server_c1.log").read_text(errors="replace")
    m = re.search(r"GPU KV cache size: ([\d,]+) tokens", log)
    log_blocks = int(m.group(1).replace(",", "")) // prof["block_size"] if m else None

    exact_counts = (chk["measured"]["hits"], chk["measured"]["queries"]) == (pred["hits"],
                                                                            pred["queries"])
    every_request = chk["cached_tokens_equal"] == chk["cached_tokens_compared"] == pred["requests"]
    c1a = c1["returncode"] == 0 and prof["calibrated"] and exact_counts and every_request
    c1b = log_blocks is not None and prof["kv_cache_blocks"] == log_blocks

    # Reported: the prefill line, and what it hides. Per-token cost by prompt length.
    pts = src["prefill_points"]
    by_len: dict[int, list[float]] = {}
    for q in pts:
        by_len.setdefault(q["uncached_tokens"], []).append(q["ttft_s"])
    med = {n: statistics.median(v) for n, v in sorted(by_len.items())}
    short = [n for n in med if n <= 1024]
    slope_short, icpt_short = statistics.linear_regression(short, [med[n] for n in short])
    p3 = c1["reported"]["phase3"]

    lines = [
        "# C1 — `kvsim calibrate` on a real T4",
        "",
        (f"vLLM {src['engine']['version']} · {prof['model']} · {prof['gpu']} · the engine's "
         f"natural capacity · wheel sha256 `{prereg['wheel']['sha256'][:16]}…` from "
         f"`{prereg['git_sha']}` · run {c1['env']['date_utc']} · "
         f"{c1['reported']['wall_clock_s']:.0f} s wall clock. "
         "Generated by `scripts/c1_analyze.py`."),
        "",
        f"**C1: {'HOLDS' if c1a and c1b else 'DOES NOT HOLD'}**",
        "",
        "| rule | registered | measured | |",
        "|---|---|---|---|",
        (f"| **C1a** cache check | exact: {pred['hits']:,} of {pred['queries']:,} tokens "
         f"(hit rate {pred['hit_rate']:.6f}), all {pred['requests']} requests equal | "
         f"{chk['measured']['hits']:,.0f} of {chk['measured']['queries']:,.0f}; "
         f"{chk['cached_tokens_equal']} of {chk['cached_tokens_compared']} requests equal; exit "
         f"{c1['returncode']} | {'✅' if c1a else '⛔'} |"),
        (f"| **C1b** capacity read | = the engine log | {prof['kv_cache_blocks']:,} blocks read · "
         f"{log_blocks:,} in the log | {'✅' if c1b else '⛔'} |"),
        "",
        "## The fitted timings — reported, not tested",
        "",
        "| | `kvsim calibrate` (C1) | Phase 3's fit (the profile the experiments use) |",
        "|---|---:|---:|",
        (f"| prefill, per uncached token | {prof['prefill_per_token_s'] * 1e3:.3f} ms "
         f"(64–2,040 tokens, R² {src['prefill_fit']['r2']:.2f}) | "
         f"{p3['prefill_per_token_s'] * 1e3:.3f} ms |"),
        (f"| decode step | {prof['decode_base_s'] * 1e3:.1f} ms + "
         f"{prof['decode_per_seq_s'] * 1e3:.2f} ms × batch (R² {src['decode_fit']['r2']:.2f}) | "
         f"{p3['decode_base_s'] * 1e3:.1f} ms + {p3['decode_per_seq_s'] * 1e3:.2f} ms × batch |"),
        f"| KV capacity | {prof['kv_cache_blocks']:,} blocks | {p3['kv_cache_blocks']:,} blocks |",
        "",
        "Prefill time per prompt length (median of three):",
        "",
        "| uncached tokens | " + " | ".join(f"{n:,}" for n in med) + " |",
        "|---" * (len(med) + 1) + "|",
        "| TTFT | " + " | ".join(f"{v * 1e3:.0f} ms" for v in med.values()) + " |",
        "| ms per token | " + " | ".join(f"{v * 1e3 / n:.2f}" for n, v in med.items()) + " |",
        "",
        ("**Prefill is not a straight line on the T4.** Up to 1,024 tokens it is "
         f"{slope_short * 1e3:.2f} ms per token ({icpt_short * 1e3:+.0f} ms) — the same as "
         f"Phase 3's {p3['prefill_per_token_s'] * 1e3:.2f} — and it gets steeper after that, "
         f"to {med[max(med)] * 1e3 / max(med):.2f} ms per token at {max(med):,}. One line over "
         f"64–{max(med):,} tokens has a negative intercept "
         f"({src['prefill_base_s_raw'] * 1e3:.0f} ms), which the command clamps to 0, and then "
         "over-predicts mid-length prompts: 512 tokens → "
         f"{prof['prefill_per_token_s'] * 512 * 1e3:.0f} ms against {med.get(512, 0) * 1e3:.0f} "
         "measured. The command's check is on hit rates, so C1 is unaffected; its timing fit is "
         "not yet good enough to size a fleet with, and the report says so."),
        "",
        ("**Decode** repeats Phase 3's oddity: one sequence alone is slower ("
         f"{src['decode_batches'][0]['median_interval_s'] * 1e3:.0f} ms) than two to sixteen "
         f"together ({min(r['median_interval_s'] for r in src['decode_batches'][1:]) * 1e3:.0f}–"
         f"{max(r['median_interval_s'] for r in src['decode_batches'][1:]) * 1e3:.0f} ms), so a "
         "line fits badly. Its prompts were 32 tokens, and decode cost may rise with context "
         "length (Phase 6's report, post hoc): these numbers describe short contexts only."),
        "",
    ]
    (OUT / "report.md").write_text("\n".join(lines) + "\n")
    print((OUT / "report.md").read_text())
    return 0 if c1a and c1b else 1


if __name__ == "__main__":
    raise SystemExit(main())
