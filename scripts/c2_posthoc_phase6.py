#!/usr/bin/env python3
"""POST HOC: does C2's fitted, context-aware timing model explain Phase 6's two live replicas?

    python scripts/c2_posthoc_phase6.py   # -> artifacts/results/c2_kaggle_t4/posthoc_phase6.md

⚠️ Post hoc, and labelled so everywhere it is quoted. The model's two context terms were added
BECAUSE Phase 6's latencies were too high, so Phase 6 is not a clean test of them. What keeps it
honest: the model's coefficients were fitted on C2's parts A and B only — they never saw a Phase 6
number — and nothing here is tuned. The clean two-replica test is a fresh registered run.

Method: Phase 6's second run recorded, for every request, which replica served it and when it was
really sent. Each replica is independent once a request is placed, so each replica's requests are
replayed through a ONE-replica simulation at their real send times — the measured placement, not a
re-simulated router. Latency percentiles by the notebook's nearest-rank rule over valid requests.
Run 1 kept only its printed summary, so it cannot be replayed.
"""

from __future__ import annotations

import dataclasses
import json
import pathlib

import yaml

from kv_routing_sim.sim.cost_model import load_profile
from kv_routing_sim.sim.engine import run
from kv_routing_sim.traces.generator import AgenticWorkload

REPO = pathlib.Path(__file__).resolve().parents[1]
P6 = REPO / "artifacts" / "results" / "phase6_kaggle_t4" / "phase6.json"
FITTED = REPO / "artifacts" / "results" / "c2_kaggle_t4" / "fitted_profile.json"
OUT = REPO / "artifacts" / "results" / "c2_kaggle_t4"


def nearest_rank(sorted_vals: list[float], q: float) -> float | None:
    if not sorted_vals:
        return None
    return sorted_vals[max(0, min(len(sorted_vals) - 1, round(q * (len(sorted_vals) - 1))))]


def replay(trace: dict, recs: list[dict], profile) -> dict:
    """Each replica's measured requests, one-replica simulation each, at their real send times."""
    ttft, hits, queries, preempt = {}, 0, 0, 0
    for replica in sorted({r["replica"] for r in recs}):
        mine = [r for r in recs if r["replica"] == replica]
        reqs = sorted((dataclasses.replace(trace[r["request_id"]],
                                           arrival_ts=max(0.0, r["send_offset_s"]))
                       for r in mine), key=lambda q: q.arrival_ts)
        res = run(reqs, policy="round-robin", n_replicas=1, seed=0, profile=profile,
                  cache_model="vllm", record_per_request=True)
        ttft.update({k: v["ttft_ms"] for k, v in res.per_request.items()})
        hits, queries, preempt = hits + res.cache_hits, queries + res.cache_queries, \
            preempt + res.preemptions
    valid = sorted(ttft[r["request_id"]] for r in recs if r["valid"])
    return {"ttft_p50_ms": nearest_rank(valid, 0.5), "ttft_p95_ms": nearest_rank(valid, 0.95),
            "hit_rate": hits / queries if queries else None, "preemptions": preempt}


def main() -> int:
    p6 = json.loads(P6.read_text())
    cfg = yaml.safe_load((REPO / "configs" / "phase6_sim2real.yaml").read_text())
    fitted, flat = load_profile(FITTED), load_profile(REPO / cfg["profile"])
    traces = {name: {q.request_id: q for q in AgenticWorkload(**spec).generate()[0]}
              for name, spec in cfg["workloads"].items()}
    rows = []
    for r in p6["runs"]:
        recs = r["requests"]
        valid = sorted(x["ttft_ms"] for x in recs if x["valid"] and x["ttft_ms"] is not None)
        meas = {"ttft_p50_ms": nearest_rank(valid, 0.5), "ttft_p95_ms": nearest_rank(valid, 0.95),
                "preemptions": r["preemptions"], "hit_rate": r["measured_hit_rate"]}
        ctx = replay(traces[r["workload"]], recs, fitted)
        cf = replay(traces[r["workload"]], recs, flat)
        rows.append({"workload": r["workload"], "policy": r["policy"], "measured": meas,
                     "context_aware": ctx, "context_free": cf,
                     "factor_p50": max(ctx["ttft_p50_ms"] / meas["ttft_p50_ms"],
                                       meas["ttft_p50_ms"] / ctx["ttft_p50_ms"]),
                     "factor_p95": max(ctx["ttft_p95_ms"] / meas["ttft_p95_ms"],
                                       meas["ttft_p95_ms"] / ctx["ttft_p95_ms"])})
    (OUT / "posthoc_phase6.json").write_text(json.dumps(rows, indent=1) + "\n")

    def s(ms: float | None) -> str:
        return "—" if ms is None else f"{ms / 1e3:.1f} s"

    lines = [
        "# POST HOC — C2's context-aware model against Phase 6's two live replicas",
        "",
        ("⚠️ Post hoc: the context terms were added because of Phase 6, so this is not a clean "
         "test. The coefficients were fitted on C2's parts A and B only and are not tuned here. "
         "Phase 6's run 2, each replica replayed at the measured placement and send times. "
         "Generated by `scripts/c2_posthoc_phase6.py`."),
        "",
        ("| run | measured p50 · p95 | context-aware model | factor p50 · p95 | context-free "
         "model | preemptions measured · model |"),
        "|---|---|---|---|---|---|",
    ]
    for x in rows:
        m, c, f = x["measured"], x["context_aware"], x["context_free"]
        lines.append(
            f"| {x['workload']} {x['policy']} | {s(m['ttft_p50_ms'])} · {s(m['ttft_p95_ms'])} | "
            f"{s(c['ttft_p50_ms'])} · {s(c['ttft_p95_ms'])} | {x['factor_p50']:.2f}× · "
            f"{x['factor_p95']:.2f}× | {s(f['ttft_p50_ms'])} · {s(f['ttft_p95_ms'])} | "
            f"{m['preemptions']} · {c['preemptions']} |")
    (OUT / "posthoc_phase6.md").write_text("\n".join(lines) + "\n")
    print((OUT / "posthoc_phase6.md").read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
